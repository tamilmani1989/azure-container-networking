namespace Microsoft.Azure.ContainerNetworking.DncRP
{
    using Microsoft.Azure.Cosmos.Table;
    using System;

    /// <summary>
    /// Defines Table entity for DelegatedSubnetConfigurationEntity
    /// </summary>
    public class DelegatedSubnetConfigurationEntity : TableEntity
    { 
        public DelegatedSubnetConfigurationEntity()
        {
        }

        public DelegatedSubnetConfigurationEntity(string subscriptionId, string resourceGroupName, string vnetName, string subnetName)
        {
            PartitionKey = subscriptionId;
            RowKey = DelegatedSubnetConfigurationEntity.GetSubnetConfigurationKey(resourceGroupName, vnetName, subnetName);

            ResourceGroup = resourceGroupName;
            VnetName = vnetName;
            Subnet = subnetName;
        }

        /// <summary>
        /// Generates the RowKey for a given Subnet
        /// </summary>
        /// <param name="resourceGroupName">resourceGroup name</param>
        /// <param name="vnetName">vnet name</param>
        /// <param name="subnet">subnet name</param>
        /// <returns></returns>
        public static string GetSubnetConfigurationKey(
            string resourceGroupName, 
            string vnetName, 
            string subnet)
        {
            return $"{resourceGroupName}_{vnetName}_{subnet}";
        }

        public override string ToString()
        {
            return $"DelegatedSubnetConfigurationEntity: PartitionKey: {PartitionKey}, RowKey: {RowKey} " +
                $"VnetResourceGuid: {VnetResourceGuid}, DelegatedSubnetGuid: {DelegatedSubnetGuid}, ResourceName :{ResourceName}, " +
                $"ProvisioningStatus: {ProvisioningStatus}, Properties {Properties}, " +
                $"ResourceGroup {ResourceGroup}, VnetName: {VnetName}, subnet: {Subnet}, " +
                $"CreatedDateUtc: {CreatedDateUtc}";
        }

        /// <summary>
        /// VNetResource Guid. This represents VnetId generated by NRP
        /// on VNET creation.
        /// </summary>
        public string VnetResourceGuid { get; set; }

        /// <summary>
        /// Resource Guid representing this DelegatedSubnet resource.
        /// This will be used by DNC-RC to get Subnet Token.
        /// </summary>
        public string DelegatedSubnetGuid { get; set; }

        /// <summary>
        /// Delegated Subnet Resource name
        /// </summary>
        public string ResourceName { get; set; }

        /// <summary>
        /// Provisioning State
        /// </summary>
        public string ProvisioningStatus { get; set; }

        /// <summary>
        /// DelegatedSubnet Properties persisted in Json format
        /// </summary>
        public string Properties { get; set; }

        /// <summary>
        /// ResourceGroup Name
        /// </summary>
        public string ResourceGroup { get; set; }

        /// <summary>
        /// VirtualNetwork name
        /// </summary>
        public string VnetName { get; set; }

        /// <summary>
        /// Subnet name
        /// </summary>
        public string Subnet { get; set; }

        /// <summary>
        /// Created DateTime
        /// </summary>
        public DateTime CreatedDateUtc { get; set; }
    }
}
