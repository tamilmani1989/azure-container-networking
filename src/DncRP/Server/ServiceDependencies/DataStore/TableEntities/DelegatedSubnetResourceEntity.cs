namespace Microsoft.Azure.ContainerNetworking.DncRP
{
    using Microsoft.Azure.Cosmos.Table;
    using System;

    /// <summary>
    /// Defines Table entity for DelegatedSubnetConfigurationEntity
    /// </summary>
    public class DelegatedSubnetResourceEntity : TableEntity
    { 
        public DelegatedSubnetResourceEntity()
        {
        }

        public DelegatedSubnetResourceEntity(string subscriptionId, string resourceGroupName, string resourceName)
        {
            PartitionKey = subscriptionId;
            RowKey = DelegatedSubnetResourceEntity.GetRowKey(resourceGroupName, resourceName);

            ResourceGroup = resourceGroupName;
            ResourceName = resourceName;
        }

        /// <summary>
        /// Generates the RowKey for a given DelegateSubnetResource
        /// </summary>
        /// <param name="resourceGroupName">resourceGroup name</param>
        /// <param name="resourceName">Resource name</param>
        /// <returns></returns>
        public static string GetRowKey(
            string resourceGroupName, 
            string resourceName)
        {
            return $"{resourceGroupName}_{resourceName}";
        }

        public override string ToString()
        {
            return $"DelegatedSubnetConfigurationEntity: PartitionKey: {PartitionKey}, RowKey: {RowKey} " +
                $"ResourceGroup {ResourceGroup}, ResourceName :{ResourceName}, " +
                $"ResourceGuid: {ResourceGuid}, Location: {Location}" +
                $"AssociatedSubnet: {AssociatedSubnetId}, ControllerId: {ControllerId}, " +
                $"VnetResourceGuid: {VnetResourceGuid}, CreatedDateUtc: {CreatedDateUtc}, " +
                $"ProvisioningStatus: {State}";
        }

        /// <summary>
        /// VNetResource Guid. This represents VnetId generated by NRP
        /// on VNET creation.
        /// </summary>
        public string VnetResourceGuid { get; set; }

        /// <summary>
        /// Resource Guid representing this DelegatedSubnet resource.
        /// This will be used by DNC-RC to get Subnet Token.
        /// </summary>
        public string ResourceGuid { get; set; }

        /// <summary>
        /// Provisioning State
        /// </summary>
        public string State { get; set; }

        /// <summary>
        /// SubnetJoinStatus. This represents dnc state on subnet join
        /// </summary>
        public string SubnetJoinStatus { get; set; }

        /// <summary>
        /// ResourceGroup Name
        /// </summary>
        public string ResourceGroup { get; set; }

        /// <summary>
        /// Delegated Subnet Resource name
        /// </summary>
        public string ResourceName { get; set; }

        /// <summary>
        /// Location
        /// </summary>
        public string Location { get; set; }

        /// <summary>
        /// Subnet Id (ARM Id of a Subnet)
        /// </summary>
        public string AssociatedSubnetId { get; set; }

        /// <summary>
        /// Controller ARM Id
        /// </summary>
        public string ControllerId { get; set; }

        /// <summary>
        /// Created DateTime
        /// </summary>
        public DateTime CreatedDateUtc { get; set; }

        internal DelegateSubnet ConvertToDelegateSubnet()
        {
            DelegateSubnetProperties properties = new DelegateSubnetProperties()
            {
                SubnetDetails = new SubnetDetails()
                {
                    Id = AssociatedSubnetId
                },
                ControllerDetails = new ControllerDetails()
                {
                    Id = ControllerId
                },
                ResourceGuid = ResourceGuid,
                State = TopLevelResourceProperties.ParseProvisioningState(State)
            };

            return new DelegateSubnet(
                PartitionKey,
                ResourceGroup,
                ResourceName,
                Location,
                properties)
            {
                VNetResourceGuid = VnetResourceGuid,
                SubnetJoinStatus = SubnetJoinStatus
            };
        }
    }
}
