namespace Microsoft.Azure.ContainerNetworking.DncRP
{
    using System;
    using System.Net;
    using System.Net.Http;
    using System.Threading.Tasks;
    using Microsoft.AspNetCore.Authorization;
    using Microsoft.AspNetCore.Http.Extensions;
    using Microsoft.AspNetCore.Mvc;
    using Microsoft.Extensions.Configuration;
    using Microsoft.Extensions.Logging;
    using Newtonsoft.Json;

    public class DelegateSubnetDefinition : ResourceDefinition
    {
        /// <summary>
        /// Gets the container group type.
        /// </summary>
        public const string DelegatedResourceType = "Microsoft.DelegatedNetwork/delegatedSubnets";

        /// <summary>
        /// Represents the DelegatedSubnetId generated by the platform.
        /// For Kubernetes Orchastrator, this Id will be used by customers to update in Node annotations 
        /// </summary>
        [JsonProperty(Required = Required.Default)]
        public Guid DelegatedSubnetId { get; set; }

        /// <summary>
        /// Initializes a new instance of the <see cref="DelegateSubnetDefinition"/> class.
        /// </summary>
        public DelegateSubnetDefinition(string subscriptionId, string resourceGroup, string vnetName, string subnetName, string delegatedId, Guid delegatedSubGuid)
        {
            // TODO validate the parameters are not null

            this.SubscriptionId = subscriptionId;
            this.ResourceGroup = resourceGroup;
            this.ResourceName = delegatedId;
            this.DelegatedSubnetId = delegatedSubGuid;

            this.isExtensionResource = true;
            this.parentResourceId = $"Microsoft.Network/virtualNetworks/{vnetName}/subnets/{subnetName}";
            this.ResourceType = DelegateSubnetDefinition.DelegatedResourceType;
        }
    }
}
